#!/bin/sh
# Builds packages/mailbox-client/bundle: one ESM file plus declarations, with
# @rat-king/envelope and @rat-king/lexicon inlined and no workspace references,
# so other repos pin it as github:joelhooks/rat-king#<sha>&path:/packages/mailbox-client/bundle.
# effect and the other npm dependencies stay external so a consumer keeps one copy of each.
# Usage: sh packages/mailbox-client/bundle.sh [out-dir]   (default: the committed bundle)
set -eu
here=$(cd "$(dirname "$0")" && pwd)
packages=$(dirname "$here")
out=${1:-$here/bundle}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

esbuild=$(cd "$packages/alchemy-nest" && node -p 'require.resolve("esbuild/bin/esbuild")')
tsc="$packages/../node_modules/.bin/tsc"

"$esbuild" "$here/src/index.ts" --bundle --format=esm --platform=neutral \
  --target=es2023 --main-fields=module,main --log-level=warning \
  --external:effect --external:'effect/*' --external:xstate \
  --external:@hpke/core --external:@ipld/dag-cbor --external:'@atproto/*' \
  --outfile="$work/index.js"

"$esbuild" "$here/src/auth.ts" --bundle --format=esm --platform=neutral \
  --target=es2023 --main-fields=module,main --log-level=warning \
  --external:effect --external:'effect/*' \
  --outfile="$work/auth.js"

"$tsc" -p "$here/tsconfig.bundle.json" --outDir "$work/emit"

mkdir -p "$work/types"
for package in mailbox-client envelope lexicon; do
  mkdir -p "$work/types/$package"
  for file in "$work/emit/$package/src"/*.d.ts; do
    perl -pe '
      s{"\@rat-king/lexicon"}{"../lexicon/mailbox-client.js"}g;
      s{"\@rat-king/envelope"}{"../envelope/envelope.js"}g;
      s{"\@rat-king/(lexicon|envelope)/([^"]+)"}{"../$1/$2.js"}g;
      s{"(\.\.?/[^"]+)\.ts"}{"$1.js"}g;
    ' "$file" > "$work/types/$package/$(basename "$file")"
  done
done

node -e '
const read = (p) => JSON.parse(require("node:fs").readFileSync(p, "utf8"));
const deps = Object.assign({}, ...["mailbox-client", "envelope", "lexicon"].map((p) => read(process.argv[1] + "/" + p + "/package.json").dependencies));
const dependencies = Object.fromEntries(Object.entries(deps).filter(([name]) => !name.startsWith("@rat-king/")).sort(([a], [b]) => a.localeCompare(b)));
process.stdout.write(JSON.stringify({
  name: "@rat-king/mailbox-client",
  version: "0.1.0",
  private: true,
  type: "module",
  sideEffects: false,
  exports: { ".": { types: "./types/mailbox-client/index.d.ts", default: "./index.js" }, "./auth": { types: "./types/mailbox-client/auth.d.ts", default: "./auth.js" } },
  dependencies,
}, null, 2) + "\n");
' "$packages" > "$work/package.json"

cat > "$work/README.md" <<'EOF'
# @rat-king/mailbox-client (bundle)

Generated by `packages/mailbox-client/bundle.sh`; do not edit. Pin it by commit:
`github:joelhooks/rat-king#<sha>&path:/packages/mailbox-client/bundle`.
`@rat-king/envelope` and `@rat-king/lexicon` are inlined; `effect` and the other
dependencies are ordinary npm dependencies, so a consumer keeps one copy of each.
Import `@rat-king/mailbox-client/auth` for the separate authentication-only entry,
which imports only Effect and does not load messaging or lifecycle providers.
Runs in Node and workerd (fetch and Web Crypto, no Node built-ins).
Types assume `strict` and `exactOptionalPropertyTypes`, as rat-king and
Mischief both compile; `skipLibCheck` hides xstate's own declaration errors.
EOF

rm -rf "$out"
mkdir -p "$out"
cp -R "$work/index.js" "$work/auth.js" "$work/types" "$work/package.json" "$work/README.md" "$out/"
